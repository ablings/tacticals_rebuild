local function proxy(parent, name, e0, e1, n0, n1, h0, h1, mat, attrs, query)
	if e0 > e1 then e0, e1 = e1, e0 end
	if n0 > n1 then n0, n1 = n1, n0 end
	local p = newPart("Part", parent, name, Vector3.new(e1 - e0, h1 - h0, n1 - n0), CFrame.new(W((e0 + e1) / 2, (n0 + n1) / 2, (h0 + h1) / 2)))
	p.Material = mat or M.Concrete
	p.Color = rgb(105, 106, 108)
	p.Transparency = 1
	p.CastShadow = false
	p.CanCollide, p.CanTouch = true, true
	p.CanQuery = query ~= false
	for k, v in attrs or {} do p:SetAttribute(k, v) end
	nProxy += 1
	return p
end
-- a slab whose underside runs along the line (e0, h0) -> (e1, h1) across n0..n1 (roof sheets, rafters, purlins)
local function slope(parent, name, e0, h0, e1, h1, n0, n1, thick, s, isProxy, ribsDownSlope)
	local a, b = W(e0, (n0 + n1) / 2, h0), W(e1, (n0 + n1) / 2, h1)
	local u = (b - a).Unit
	local v = Vector3.new(-u.Y, u.X, 0)
	if v.Y < 0 then v = -v end
	local c = (a + b) / 2 + v * (thick / 2)
	local p
	if ribsDownSlope then -- local X along the hall, local Z down the slope: the material's ribs run eave to ridge
		p = newPart("Part", parent, name, Vector3.new(math.abs(n1 - n0), thick, (b - a).Magnitude), CFrame.fromMatrix(c, Vector3.new(0, 0, 1), v))
	else
		p = newPart("Part", parent, name, Vector3.new((b - a).Magnitude, thick, math.abs(n1 - n0)), CFrame.fromMatrix(c, u, v))
	end
	if isProxy then
		p.Material, p.Transparency, p.CastShadow = s, 1, false
		p.CanCollide, p.CanQuery, p.CanTouch = true, true, true
		nProxy += 1
		return p
	end
	return style(p, s)
end
-- vertical cylinder (axis = world Y) at plan (e, n), from h0 to h1
local function vcyl(parent, name, e, n, h0, h1, dia, s)
	local p = newPart("Part", parent, name, Vector3.new(h1 - h0, dia, dia), CFrame.new(W(e, n, (h0 + h1) / 2)) * CFrame.Angles(0, 0, math.pi / 2))
	p.Shape = Enum.PartType.Cylinder
	return style(p, s)
end
-- horizontal cylinder along plan e (axis world X) or n (axis world Z)
local function hcyl(parent, name, e0, e1, n0, n1, h, dia, s)
	local len = math.max(math.abs(e1 - e0), math.abs(n1 - n0))
	local cf = CFrame.new(W((e0 + e1) / 2, (n0 + n1) / 2, h))
	if math.abs(n1 - n0) > math.abs(e1 - e0) then cf = cf * CFrame.Angles(0, math.pi / 2, 0) end
	local p = newPart("Part", parent, name, Vector3.new(len, dia, dia), cf)
	p.Shape = Enum.PartType.Cylinder
	return style(p, s)
end
-- a WedgePart: plan footprint e0..e1 x n0..n1, h0..h1, full height on the side `high` ("e+", "e-", "n+", "n-")
local function wedge(parent, name, e0, e1, n0, n1, h0, h1, high, s, isProxy)
	if e0 > e1 then e0, e1 = e1, e0 end
	if n0 > n1 then n0, n1 = n1, n0 end
	local c = W((e0 + e1) / 2, (n0 + n1) / 2, (h0 + h1) / 2)
	-- LookVector points at the LOW end (the wedge's slope rises toward its back, +Z local)
	local lowDir = ({ ["e+"] = Vector3.new(1, 0, 0), ["e-"] = Vector3.new(-1, 0, 0), ["n+"] = Vector3.new(0, 0, -1), ["n-"] = Vector3.new(0, 0, 1) })[high]
	local alongE = high:sub(1, 1) == "e"
	local size = alongE and Vector3.new(n1 - n0, h1 - h0, e1 - e0) or Vector3.new(e1 - e0, h1 - h0, n1 - n0)
	local p = newPart("WedgePart", parent, name, size, CFrame.lookAt(c, c + lowDir))
	if isProxy then
		p.Material, p.Transparency, p.CastShadow = s, 1, false
		p.CanCollide, p.CanQuery, p.CanTouch = true, true, true
		nProxy += 1
		return p
	end
	return style(p, s)
end
