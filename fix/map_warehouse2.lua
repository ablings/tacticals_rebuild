local nArt, nProxy, nLights = 0, 0, 0
local function newPart(class, parent, name, size, cf)
	local p = Instance.new(class or "Part")
	p.Name = name
	p.Anchored = true
	p.Size = size
	p.CFrame = cf
	p.TopSurface, p.BottomSurface = Enum.SurfaceType.Smooth, Enum.SurfaceType.Smooth
	p.Parent = parent
	return p
end
local function style(p, s)
	p.Material = s[1]
	if s[2] then p.MaterialVariant = s[2] end
	p.Color = s[3]
	p.Transparency = s[4] or 0
	p.Reflectance = s[5] or 0
	p.CanCollide, p.CanQuery, p.CanTouch = false, false, false
	nArt += 1
	return p
end
-- an art box from plan bounds
local function box(parent, name, e0, e1, n0, n1, h0, h1, s)
	if e0 > e1 then e0, e1 = e1, e0 end
	if n0 > n1 then n0, n1 = n1, n0 end
	local p = newPart("Part", parent, name, Vector3.new(e1 - e0, h1 - h0, n1 - n0), CFrame.new(W((e0 + e1) / 2, (n0 + n1) / 2, (h0 + h1) / 2)))
	return style(p, s)
end
