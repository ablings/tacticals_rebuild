local tmp = workspace:FindFirstChild("_CheckHeliTmp"); if tmp then tmp:Destroy() end
tmp = Instance.new("Folder"); tmp.Name = "_CheckHeliTmp"; tmp.Parent = workspace
local function tpart(cf, size, name, shape)
	local p = Instance.new("Part"); p.Anchored = true; p.CanCollide = false; p.CanQuery = false; p.CanTouch = false; p.Transparency = 1
	if shape then p.Shape = shape end
	p.Size = size; p.CFrame = cf; p.Name = name; p.Parent = tmp; return p
end
local function bodies(m) -- inflated by m
	local list = {}
	for _, q in PROXIES do
		table.insert(list, tpart(CFrame.new(PIVOT + Vector3.new(q[1], q[2], q[3])), Vector3.new(q[4], q[5], q[6]) + Vector3.one * 2 * m, q[7]))
	end
	local mhub = Vector3.new(mast.X, DISC_Y, mast.Z)
	table.insert(list, tpart(CFrame.new(mhub) * CFrame.Angles(0, 0, math.pi / 2), Vector3.new(DISC_T + 2 * m, 2 * (R_MAIN + m), 2 * (R_MAIN + m)), "MainRotorDisc", Enum.PartType.Cylinder))
	table.insert(list, tpart(CFrame.new(mast.X, 10.515, mast.Z), Vector3.new(3.82, 1.13, 3.82) + Vector3.one * 2 * m, "MainRotorHub"))
	table.insert(list, tpart(CFrame.lookAt(hub, hub + ax) * CFrame.Angles(0, math.pi / 2, 0), Vector3.new(0.3 + 2 * m, 2 * (R_TAIL + m), 2 * (R_TAIL + m)), "TailRotorDisc", Enum.PartType.Cylinder))
	local base = {}; for _, p in list do base[p] = p.CFrame end
	return list, base
end
local list, base = bodies(0)
say(("  test bodies: %d proxies + main disc r %.1f + hub + tail disc r %.2f"):format(#PROXIES, R_MAIN, R_TAIL))

-- swept bounds -> map parts to test (visible only), made queryable
local lo, hi = Vector3.one * math.huge, -Vector3.one * math.huge
for _, e in frames do
	local T = liftT(e)
	for _, p in list do
		local cf = T * base[p]; local s = p.Size.Magnitude / 2
		lo = lo:Min(cf.Position - Vector3.one * s); hi = hi:Max(cf.Position + Vector3.one * s)
	end
	local c = liftCam(e); lo = lo:Min(c); hi = hi:Max(c)
end
lo -= Vector3.one * 3; hi += Vector3.one * 3
local saveQ, mapParts = {}, {}
for _, d in LM:GetDescendants() do
	if d:IsA("BasePart") and not d:IsDescendantOf(heli) and d ~= hp and d ~= cp and d.Transparency < 1 then
		local p, s = d.Position, d.Size.Magnitude / 2
		if p.X + s > lo.X and p.X - s < hi.X and p.Y + s > lo.Y and p.Y - s < hi.Y and p.Z + s > lo.Z and p.Z - s < hi.Z then
			saveQ[d] = d.CanQuery; d.CanQuery = true; table.insert(mapParts, d)
		end
	end
end
say(("  swept volume %s .. %s; visible map parts in it: %d"):format(f3(lo), f3(hi), #mapParts))
local op = OverlapParams.new(); op.FilterType = Enum.RaycastFilterType.Include; op.FilterDescendantsInstances = mapParts

local function short(h) if typeof(h) == "RaycastResult" then h = h.Instance end return (h:GetFullName():gsub("Workspace.LobbyMap.", "")) end
local FLOORISH = {"E_Floor", "E_Helipad", "TieDown", "Rim", "Stencil", "EdgeBand", "Hazard", "E_Lines"}
local function isFloor(h)
	local top = h.Position.Y + h.Size.Magnitude / 2
	for _, k in FLOORISH do if h:GetFullName():find(k) then return true end end
	return top < 0.4
end

local ok, err = pcall(function()
	-- 4. sweep at 30 Hz, margin 0 = pass/fail ------------------------------------------------------------------
	local hits, contacts, barrierUntil, seen = {}, {}, nil, {}
	local liftoff = nil
	for i, e in frames do
		local T = liftT(e)
		if not liftoff and (T * pivotCF).Position.Y - pivotCF.Position.Y > 0.15 then liftoff = e end
		for _, p in list do
			p.CFrame = T * base[p]
			for _, h in workspace:GetPartsInPart(p, op) do
				if h == b then barrierUntil = e
				elseif isFloor(h) and not liftoff then
					contacts[p.Name .. " x " .. short(h)] = true
				else
					local k = p.Name .. " x " .. short(h)
					if not seen[k] then seen[k] = e; table.insert(hits, k) end
				end
			end
		end
		if i % 10 == 0 then task.wait() end
	end
	local nc = 0; for _ in contacts do nc += 1 end
	say(("SWEEP (margin 0, %d frames, e 0..%.2f): overlaps %d"):format(#frames, E_END, #hits))
	for _, k in hits do say(("  FAIL overlap %s first @e%.2f"):format(k, seen[k])) end
	if #hits > 0 then fails += 1 end
	say(("  wheel/pad contacts before lift-off (e < %.2f, allowed): %d"):format(liftoff or -1, nc))
	say(("  ExfilBarrier ForceField curtain: rotor crosses it until e %s (trigger, not geometry; allowed)"):format(barrierUntil and string.format("%.2f", barrierUntil) or "never"))

	-- 5. clearance report: inflated bodies, what comes within 1.0 / 0.5 / 0.25 studs -----------------------------
	for _, p in list do p:Destroy() end
	local close = {}
	for _, m in MARGINS do
		local L, B = bodies(m)
		for i, e in frames do
			if e > (liftoff or 0) + 0.1 then
				local T = liftT(e)
				for _, p in L do
					p.CFrame = T * B[p]
					for _, h in workspace:GetPartsInPart(p, op) do
						if h ~= b and not isFloor(h) then
							local k = short(h)
							if not close[k] or close[k][1] > m then close[k] = {m, e, p.Name} end
						end
					end
				end
			end
			if i % 10 == 0 then task.wait() end
		end
		for _, p in L do p:Destroy() end
	end
	local cl = {}; for k, v in close do table.insert(cl, {k, v}) end
	table.sort(cl, function(x, y) return x[2][1] < y[2][1] end)
	say(("CLEARANCE (info, after lift-off): map parts within 1.0 stud of the heli at some frame: %d"):format(#cl))
	for _, c in cl do say(("  < %.2f  %s  (%s @e%.2f)"):format(c[2][1], c[1], c[2][3], c[2][2])) end
	list, base = bodies(0)

	-- 6. camera: start shot + lift path -------------------------------------------------------------------------
	local losParts = {} -- the ExfilBarrier ForceField curtain is see-through: not an occluder
	for _, d in mapParts do if d ~= b then table.insert(losParts, d) end end
	local incl = RaycastParams.new(); incl.FilterType = Enum.RaycastFilterType.Include; incl.FilterDescendantsInstances = losParts
	local ball = tpart(CFrame.new(), Vector3.one * 1.0, "CamBall", Enum.PartType.Ball)
	local inside, blocked, through, inMap, rotorHidden, outFrame, hidWhat = {}, {}, {}, {}, 0, 0, {}
	local prev = Vector3.new(120, 9, -18)
	local tan = math.tan(math.rad(35)) -- 70 deg vertical FOV
	for _, e in frames do
		local T = liftT(e)
		local cam, tgt = liftCam(e), (T * pivotCF).Position
		for _, p in list do
			local rel = (T * base[p]):PointToObjectSpace(cam)
			local hs = p.Size / 2 + Vector3.new(0.5, 0.5, 0.5)
			if p.Shape == Enum.PartType.Block and math.abs(rel.X) < hs.X and math.abs(rel.Y) < hs.Y and math.abs(rel.Z) < hs.Z then
				table.insert(inside, ("%s @e%.2f"):format(p.Name, e)); break end
		end
		-- rotor discs never sweep past the lens (within 1.5 studs of either disc)
		for _, p in list do
			if p.Shape == Enum.PartType.Cylinder then
				local rel = (T * base[p]):PointToObjectSpace(cam)
				if math.abs(rel.X) < p.Size.X / 2 + 1.5 and Vector2.new(rel.Y, rel.Z).Magnitude < p.Size.Y / 2 + 1.5 then
					table.insert(inside, ("%s near lens @e%.2f"):format(p.Name, e)) end
			end
		end
		ball.CFrame = CFrame.new(cam)
		for _, h in workspace:GetPartsInPart(ball, op) do table.insert(inMap, ("%s @e%.2f"):format(short(h), e)) end
		local mv = cam - prev
		if mv.Magnitude > 1e-3 then local h = workspace:Raycast(prev, mv, incl); if h then table.insert(through, ("%s @e%.2f"):format(short(h), e)) end end
		prev = cam
		if e <= LIFT_T then -- fully visible part of the shot
			local h = workspace:Raycast(cam, tgt - cam, incl)
			if h then table.insert(blocked, ("%s @e%.2f"):format(short(h), e)) end
			local rh = (T * CFrame.new(mast.X, 10.5, mast.Z)).Position
			local hh = workspace:Raycast(cam, rh - cam, incl)
			if hh then rotorHidden += 1; hidWhat[short(hh)] = (hidWhat[short(hh)] or "") .. string.format(" %.2f", e) end
			-- heli in frame: nose, tail, rotor hub vs a 70 deg (v) x 16:9 frustum looking at the cabin
			local look = CFrame.lookAt(cam, tgt)
			for _, pt in {Vector3.new(133, 3, -13.6), Vector3.new(134, 9, 22.7), Vector3.new(133, 10.5, 0)} do
				local r = look:PointToObjectSpace((T * CFrame.new(pt)).Position)
				if r.Z > -0.1 or math.abs(r.Y / -r.Z) > tan or math.abs(r.X / -r.Z) > tan * 16 / 9 then outFrame += 1; break end
			end
		end
	end
	say(("CAMERA  inside heli %d %s; inside map geometry %d %s; passes through geometry %d %s"):format(#inside, table.concat(inside, ", "),
		#inMap, table.concat(inMap, ", "), #through, table.concat(through, ", ")))
	say(("  map parts between camera and cabin (e <= LIFT_T) %d %s; rotor hub hidden %d frames; heli body out of frame %d frames"):format(
		#blocked, table.concat(blocked, ", "), rotorHidden, outFrame))
	for k, v in hidWhat do say(("  rotor hub behind %s at e%s"):format(k, v)) end
	if #inside > 0 or #inMap > 0 or #through > 0 or #blocked > 0 then fails += 1 end

	-- 7. jump arc barrier -> HatchPoint against the heli (R15 box); ExfilFX moves the character by CFrame
	local pathHits = {}
	for _, z in {-10, 0, 10} do
		local p0 = Vector3.new(127.4, 3.1, z)
		for a = 0, 1, 0.1 do
			local pos = p0:Lerp(hp.Position, a) + Vector3.new(0, math.sin(a * math.pi) * 4.5, 0)
			for _, p in list do
				if p.Shape == Enum.PartType.Block then
					local rel = p.CFrame:PointToObjectSpace(pos); local hs = p.Size / 2 + Vector3.new(0.8, 2.4, 0.5)
					if math.abs(rel.X) < hs.X and math.abs(rel.Y) < hs.Y and math.abs(rel.Z) < hs.Z then pathHits[p.Name] = true end
				end
			end
		end
	end
	local ph = {}; for k in pathHits do table.insert(ph, k) end
	say(("JUMP  arc barrier -> HatchPoint (R15 box) touches heli proxies %d %s (info: the door frame; the character is CFramed)"):format(#ph, table.concat(ph, ", ")))

	-- 8. path summary every 0.3 s (for the notes)
	local rows = {}
	for e = 0, E_END + 1e-6, 0.3 do
		local T = liftT(e); local c = (T * pivotCF).Position; local m = (T * CFrame.new(mast.X, DISC_Y, mast.Z)).Position
		local rx, ry, rz = (T - T.Position):ToOrientation()
		table.insert(rows, ("  e%.1f cabin %s mast-top %s pitch/yaw/roll %d/%d/%d"):format(e, f3(c), f3(m), math.round(math.deg(rx)), math.round(math.deg(ry)), math.round(math.deg(rz))))
	end
	say("PATH\n" .. table.concat(rows, "\n"))
end)
if not ok then bad("check error: " .. tostring(err)) end

