		if p.X + s > region[1].X and p.X - s < region[2].X and p.Y + s > region[1].Y and p.Y - s < region[2].Y and p.Z + s > region[1].Z and p.Z - s < region[2].Z then
			saveQ[d] = d.CanQuery; d.CanQuery = true; table.insert(mapParts, d)
		end
	end
end
local op = OverlapParams.new(); op.FilterType = Enum.RaycastFilterType.Include; op.FilterDescendantsInstances = mapParts

local pivotCF = cp.CFrame
local function lift(e)
	local off = CFrame.new(e * e * 3.2, math.min(e, 4) ^ 1.5 * 2.2, 0) * CFrame.Angles(0, 0, -math.min(e * 0.06, 0.18))
	return CFrame.new(pivotCF.Position) * off * CFrame.new(-pivotCF.Position)
end
local FLOORISH = {"E_Floor", "E_Helipad", "TieDown", "Rim", "Stencil", "EdgeBand", "Hazard"}
local function isFloor(h) for _, k in FLOORISH do if h:GetFullName():find(k) then return true end end return false end

for _, set in sets do
	local label, list = set[1], set[2]
	say(label .. ": " .. #list .. " test bodies")
	-- 3. static clips (pad, hangar roof, props); floor/markings contacts listed separately
	local clips, contacts, seen = {}, {}, {}
	local base = {}
	for _, p in list do base[p] = p.CFrame end
	for _, p in list do
		for _, h in workspace:GetPartsInPart(p, op) do
			local k = p.Name .. " x " .. h:GetFullName():gsub("Workspace.LobbyMap.", "")
			if not seen[k] then seen[k] = true; table.insert(isFloor(h) and contacts or clips, k) end
		end
	end
	say(("  static clips %d %s"):format(#clips, table.concat(clips, "; ")))
	say(("  floor/marking contacts %d %s"):format(#contacts, #contacts > 12 and "(first 12) " .. table.concat(contacts, "; ", 1, 12) or table.concat(contacts, "; ")))
	if #clips > 0 then fails += 1 end
	-- lowest point vs pad top
	local low = math.huge; for _, p in list do if not p.Name:find("Disc") then local _, sz = p.CFrame, p.Size; local e = p.CFrame:VectorToWorldSpace(sz / 2); low = math.min(low, p.Position.Y - math.abs(p.CFrame.UpVector.Y * sz.Y / 2) - math.abs(p.CFrame.RightVector.Y * sz.X / 2) - math.abs(p.CFrame.LookVector.Y * sz.Z / 2)) end end
	say(("  lowest test body bottom y %.2f (pad/floor top ~0.07-0.16)"):format(low))
	-- 4. ExfilFX lift sweep (e = 0.1 .. 2.6): new overlaps beyond the static ones
	local sweep, sseen, late = {}, {}, {}
	for e = 0.1, 2.61, 0.1 do
		local T = lift(e)
		for _, p in list do
			p.CFrame = T * base[p]
			for _, h in workspace:GetPartsInPart(p, op) do
				local k = p.Name .. " x " .. h:GetFullName():gsub("Workspace.LobbyMap.", "")
				if not seen[k] and not sseen[k] then sseen[k] = true; table.insert(e >= 1.95 and late or sweep, ("%s @e%.1f"):format(k, e)) end
			end
		end
	end
	for _, p in list do p.CFrame = base[p] end
	say(("  lift sweep new overlaps e<1.95: %d %s"):format(#sweep, table.concat(sweep, "; ")))
	say(("  lift sweep late (e>=1.95, the ExfilFX path crosses the east-edge gantry; old model too; warn only): %d %s"):format(#late, table.concat(late, "; ")))
	if #sweep > 0 then fails += 1 end
	-- 5. cutscene camera: never inside a heli test body; map parts never between the camera and the cabin target
	local inside, blocked = {}, {}
	local incl = RaycastParams.new(); incl.FilterType = Enum.RaycastFilterType.Include; incl.FilterDescendantsInstances = mapParts
	for e = 0, 2.61, 0.1 do
		local T = lift(e)
		local cam = e == 0 and Vector3.new(120, 9, -18) or Vector3.new(120, 9 + e * 1.5, -18 - e * 2)
		local tgt = e == 0 and Vector3.new(133, 4, 2) or (T * pivotCF).Position
		for _, p in list do
			local rel = (T * base[p]):PointToObjectSpace(cam)
			local hs = p.Size / 2 + Vector3.new(0.3, 0.3, 0.3)
			if math.abs(rel.X) < hs.X and math.abs(rel.Y) < hs.Y and math.abs(rel.Z) < hs.Z then table.insert(inside, ("%s @e%.1f"):format(p.Name, e)); break end
		end
		local h = workspace:Raycast(cam, tgt - cam, incl)
		if h then table.insert(blocked, ("%s @e%.1f"):format(h.Instance.Name, e)) end
	end
	say(("  camera inside heli bodies %d %s; map parts between camera and cabin %d %s"):format(#inside, table.concat(inside, ", "),
		#blocked, table.concat(blocked, ", ")))
	if #inside > 0 or #blocked > 0 then fails += 1 end
	-- 6. jump path HatchPoint -> door: map parts in the arc (ExfilFX: p0 -> HatchPoint, +4.5 arc), checked from the barrier ends
	local pathHits = {}
	for _, z in {-10, 0, 10} do
		local p0 = Vector3.new(127.4, 3.1, z)
		for a = 0, 1, 0.1 do
			local pos = p0:Lerp(hp.Position, a) + Vector3.new(0, math.sin(a * math.pi) * 4.5, 0)
			for _, p in list do
				local rel = p.CFrame:PointToObjectSpace(pos); local hs = p.Size / 2 + Vector3.new(0.8, 2.4, 0.5)
				if math.abs(rel.X) < hs.X and math.abs(rel.Y) < hs.Y and math.abs(rel.Z) < hs.Z then pathHits["heli:" .. p.Name] = true end
			end
		end
	end
	local ph = {}; for k in pathHits do table.insert(ph, k) end
	say(("  jump arc barrier -> HatchPoint (R15 box) hits heli bodies %d %s"):format(#ph, table.concat(ph, ", ")))
end

tmp:Destroy()
for p, v in saveQ do p.CanQuery = v end
say(("RESULT fails %d"):format(fails))
return table.concat(out, "\n")
