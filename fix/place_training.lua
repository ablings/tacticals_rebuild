local function hideOne(inst)
	if inst:GetAttribute("TrainingHidden") then return 0 end
	if inst:IsA("BasePart") then
		inst:SetAttribute("Training_T", inst.Transparency); inst:SetAttribute("Training_C", inst.CanCollide)
		inst:SetAttribute("Training_Q", inst.CanQuery); inst:SetAttribute("Training_Tc", inst.CanTouch)
		inst.Transparency = 1; inst.CanCollide = false; inst.CanQuery = false; inst.CanTouch = false
	elseif inst:IsA("Decal") or inst:IsA("Texture") then
		inst:SetAttribute("Training_T", inst.Transparency); inst.Transparency = 1
	elseif inst:IsA("Light") or inst:IsA("ParticleEmitter") or inst:IsA("Beam") or inst:IsA("SurfaceGui") or inst:IsA("BillboardGui") then
		inst:SetAttribute("Training_E", inst.Enabled); inst.Enabled = false
	else
		return 0
	end
	-- RoomFX switches RoomLight lights on by tag: untag hidden carriers (kept in an attribute for UNDO)
	if CS:HasTag(inst, "RoomLight") then CS:RemoveTag(inst, "RoomLight"); inst:SetAttribute("Training_Tags", "RoomLight") end
	inst:SetAttribute("TrainingHidden", true)
	return 1
end
local function unhideOne(inst)
	if not inst:GetAttribute("TrainingHidden") then return 0 end
	if inst:IsA("BasePart") then
		inst.Transparency = inst:GetAttribute("Training_T"); inst.CanCollide = inst:GetAttribute("Training_C")
		inst.CanQuery = inst:GetAttribute("Training_Q"); inst.CanTouch = inst:GetAttribute("Training_Tc")
	elseif inst:IsA("Decal") or inst:IsA("Texture") then
		inst.Transparency = inst:GetAttribute("Training_T")
	else
		inst.Enabled = inst:GetAttribute("Training_E")
	end
	local tags = inst:GetAttribute("Training_Tags")
	if tags then for _, t in string.split(tags, ",") do CS:AddTag(inst, t) end end
	for _, a in {"TrainingHidden", "Training_T", "Training_C", "Training_Q", "Training_Tc", "Training_E", "Training_Tags"} do inst:SetAttribute(a, nil) end
	return 1
end
local function hideTree(root) local n = hideOne(root); for _, d in root:GetDescendants() do n += hideOne(d) end; return n end

