local SS, CS = game:GetService("ServerStorage"), game:GetService("CollectionService")
local MS = game:GetService("MaterialService")
local CH = game:GetService("ChangeHistoryService")
local LM = workspace:WaitForChild("LobbyMap")
local heli = LM:FindFirstChild("Heli"); assert(heli, "LobbyMap.Heli missing")
local log = {}
local function say(...) local t = {} for _, v in ipairs({...}) do table.insert(t, tostring(v)) end table.insert(log, table.concat(t, " ")) end
local function f3(v) return string.format("(%.2f,%.2f,%.2f)", v.X, v.Y, v.Z) end
local function folder(parent, name)
	local f = parent:FindFirstChild(name); if not f then f = Instance.new("Folder"); f.Name = name; f.Parent = parent end; return f
end
local RR = folder(SS, "_RebuildRemoved")

local function findImport()
	-- the container holding K_Scale7 (Workspace or ServerStorage, outside LobbyMap / _RebuildRemoved)
	for _, root in {workspace, SS} do
		for _, d in root:GetDescendants() do
			if d.Name == "K_Scale7" and d:IsA("BasePart") and not d:IsDescendantOf(LM) and not d:IsDescendantOf(RR) then return d.Parent, d end
		end
	end
end

local function undo()
	local hx = heli:FindFirstChild("HX")
	local back = 0
	if hx then
		local imp = folder(SS, "heli_import")
		for _, p in hx:GetChildren() do
			if p:IsA("BasePart") then
				local cf, sz = p:GetAttribute("HeliKit_ImportCF"), p:GetAttribute("HeliKit_ImportSize")
				if cf then p.CFrame = cf end
				if sz then p.Size = sz end
				p:SetAttribute("Rotor", nil)
				p.Parent = imp
			end
		end
		hx:Destroy()
		for _, n in {"K_Scale7", "K_Marker7"} do local k = RR:FindFirstChild(n); if k then k.Parent = imp end end
	end
	local old = RR:FindFirstChild("Heli_Old")
	if old then
		for _, p in old:GetChildren() do p.Parent = heli; p:SetAttribute("HeliKit_OldParent", nil); back += 1 end
		old:Destroy()
	end
	for _, a in {"TailHub", "TailAxis"} do
		local o = heli:GetAttribute("HeliKit_Orig" .. a)
		if o ~= nil then heli:SetAttribute(a, o); heli:SetAttribute("HeliKit_Orig" .. a, nil) end
	end
	say("undo: old meshes back", back, "kit removed", hx and "yes" or "no")
end

CH:SetWaypoint("place_heli start")
undo()
if UNDO then CH:SetWaypoint("place_heli UNDO"); return table.concat(log, "\n") end

local src, cube = findImport()
if not src then return table.concat(log, "\n") .. "\nNO IMPORT FOUND: import kit/heli.fbx first (K_Scale7 missing). Old helicopter left in place." end
local s = cube.Size.X / K_SIZE
say("import:", src:GetFullName(), "scale", string.format("%.4f", s), "cube size", f3(cube.Size))
local mark = src:FindFirstChild("K_Marker7")
local turn = CFrame.identity
if mark then
	local rel = (mark.Position - cube.Position) / s
	if rel.X * MARK_REL.X < 0 then turn = CFrame.Angles(0, math.pi, 0) end
	say("marker rel", f3(rel), "turned", tostring(turn ~= CFrame.identity))
end
local origin = cube.Position - turn:VectorToWorldSpace(K_CENTRE * s)   -- FBX origin (pivot frame) in the import

-- old meshes out (moved, not deleted)
local old = folder(RR, "Heli_Old")
local nOld = 0
for _, p in heli:GetChildren() do
	if p:IsA("BasePart") then p:SetAttribute("HeliKit_OldParent", heli:GetFullName()); p.Parent = old; nOld += 1 end
end
say("old meshes moved to ServerStorage._RebuildRemoved.Heli_Old:", nOld)

local hx = Instance.new("Folder"); hx.Name = "HX"; hx:SetAttribute("Note", "UH-60-class kit (kit/heli.fbx), fix/place_heli.lua"); hx.Parent = heli
local placed, maxDev, missing = 0, 0, {}
local variant = MS:FindFirstChild("TacMetal", true)
for name, m in MESH do
	local p = src:FindFirstChild(name)
	if not (p and p:IsA("MeshPart")) then table.insert(missing, name); continue end
	p:SetAttribute("HeliKit_ImportCF", p.CFrame); p:SetAttribute("HeliKit_ImportSize", p.Size)
	local loc = turn:VectorToObjectSpace(p.Position - origin) / s
	local want = Vector3.new(m[12], m[13], m[14])
	maxDev = math.max(maxDev, (loc - want).Magnitude)
	p.Size = Vector3.new(m[15], m[16], m[17])
	p.CFrame = CFrame.new(PIVOT + want) * (turn:Inverse() * p.CFrame.Rotation)
	p.Color = Color3.fromRGB(m[1], m[2], m[3]); p.Material = Enum.Material[m[4]]
	p.MaterialVariant = (m[4] == "Metal" and variant) and variant.Name or ""
	p.Anchored = true; p.CanCollide = m[5]; p.CanQuery = m[6]; p.CanTouch = false
	p.CollisionFidelity = Enum.CollisionFidelity[m[7]]
	p.CastShadow = m[8]; p.Transparency = m[9]; p.Reflectance = m[10]
	p:SetAttribute("NotCover", true); p:SetAttribute("HeliKit", true)
	if m[11] ~= "" then p:SetAttribute("Rotor", m[11]) end
	p.Parent = hx
	placed += 1
end
say("placed", placed, "meshes; max import-position deviation from the manifest", string.format("%.3f", maxDev), "studs",
	#missing > 0 and ("MISSING " .. table.concat(missing, ", ")) or "")
for _, n in {"K_Scale7", "K_Marker7"} do local k = src:FindFirstChild(n); if k then k.Parent = RR end end
if #src:GetChildren() == 0 and src ~= workspace and src ~= SS then src:Destroy() end

for a, v in {TailHub = TAIL_HUB, TailAxis = TAIL_AXIS} do
	if heli:GetAttribute("HeliKit_Orig" .. a) == nil then heli:SetAttribute("HeliKit_Orig" .. a, heli:GetAttribute(a)) end
	heli:SetAttribute(a, v)
end
say("Heli Mast", heli:GetAttribute("Mast"), "TailHub", heli:GetAttribute("TailHub"), "TailAxis", heli:GetAttribute("TailAxis"),
	"pivot", f3(heli:GetPivot().Position))
CH:SetWaypoint("place_heli")
return table.concat(log, "\n")
