"""gen_install.py: writes art/anim/weapons/install_sources.lua from out/anim_weapons/json/*.json and the published ids in
art/anim/weapons/published.json ({clip: "rbxassetid://..."}). The Lua (re)creates every KeyframeSequence in
ReplicatedStorage.Repository.AnimationSources with its markers and PublishedId; idempotent; run in Studio (command bar or
MCP execute_luau) in a place copy.
  python gen_install.py [clip ...]   (default: every clip that has a JSON)"""
import json, os, sys, glob
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(H, "..", "..", "..", "out", "anim_weapons", "json")
pub = json.load(open(os.path.join(H, "published.json"))) if os.path.exists(os.path.join(H, "published.json")) else {}
names = sys.argv[1:] or sorted(os.path.basename(p)[:-5] for p in glob.glob(os.path.join(D, "*.json")))
clips = []
for n in names:
    c = json.load(open(os.path.join(D, n + ".json")))
    c.pop("quality", None); c.pop("nkeys", None)
    if n in pub:
        c["attrs"]["PublishedId"] = pub[n]
    clips.append(c)
build = open(os.path.join(H, "studio", "build_clips.lua"), encoding="utf-8").read()
out = os.path.join(H, "install_sources.lua")
with open(out, "w", encoding="utf-8") as f:
    f.write("-- install_sources.lua (generated by art/anim/weapons/tools/gen_install.py; do not edit by hand)\n")
    f.write("-- %d weapon / melee / gadget clips with markers and PublishedId. Run in Studio in a place copy.\n" % len(clips))
    f.write("local CLIPS_JSON = [==[" + json.dumps(clips, separators=(",", ":")) + "]==]\n")
    f.write(build.replace('if old and old:GetAttribute("SourceHash") == clip.attrs.SourceHash then keepId = old:GetAttribute("PublishedId") end',
                          'if clip.attrs.PublishedId == nil and old and old:GetAttribute("SourceHash") == clip.attrs.SourceHash then keepId = old:GetAttribute("PublishedId") end'))
print("wrote", out, len(clips), "clips,", sum(1 for c in clips if "PublishedId" in c["attrs"]), "with ids")
