"""gen_install.py: writes art/anim/reload_variants/install_sources.lua from out/anim_reload_variants/json/*.json and the
published ids in art/anim/reload_variants/published.json ({clip: "rbxassetid://..."}). The Lua (re)creates each variant
KeyframeSequence in ReplicatedStorage.Repository.AnimationSources with markers, attributes (BaseReload, RoundsLeft, Source)
and PublishedId. Idempotent; run in Studio (command bar or MCP execute_luau) in a place copy.
  python gen_install.py"""
import json, os, glob
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(H, "..", "..", "..")
D = os.path.join(R, "out", "anim_reload_variants", "json")
P = os.path.join(H, "published.json")
pub = json.load(open(P)) if os.path.exists(P) else {}
clips = []
for p in sorted(glob.glob(os.path.join(D, "*.json"))):
    c = json.load(open(p))
    c.pop("quality", None); c.pop("nkeys", None)
    if c["name"] in pub:
        c["attrs"]["PublishedId"] = pub[c["name"]]
    clips.append(c)
build = open(os.path.join(H, "..", "weapons", "studio", "build_clips.lua"), encoding="utf-8").read()
build = build.replace('if old and old:GetAttribute("SourceHash") == clip.attrs.SourceHash then keepId = old:GetAttribute("PublishedId") end',
                      'if clip.attrs.PublishedId == nil and old and old:GetAttribute("SourceHash") == clip.attrs.SourceHash then keepId = old:GetAttribute("PublishedId") end')
build = build.replace("[anim-weapons]", "[reload-variants]")
out = os.path.join(H, "install_sources.lua")
with open(out, "w", encoding="utf-8") as f:
    f.write("-- install_sources.lua (generated by art/anim/reload_variants/tools/gen_install.py; do not edit by hand)\n")
    f.write("-- %d ammo-aware reload variants (+Left mirrors) with markers and PublishedId. Run in Studio in a place copy.\n" % len(clips))
    f.write("local CLIPS_JSON = [==[" + json.dumps(clips, separators=(",", ":")) + "]==]\n")
    f.write(build)
print("wrote", out, len(clips), "clips,", sum(1 for c in clips if "PublishedId" in c["attrs"]), "with ids")
