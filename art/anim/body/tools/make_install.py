"""make_install.py: writes art/anim/body/install_sources.lua = build_clips.lua + every final body clip's JSON + the
published ids (art/anim/body/published.json {name: "rbxassetid://..."}). Run the .lua in Studio (command bar / MCP,
Edit mode): it (re)creates ReplicatedStorage.Repository.AnimationSources.<Clip> with markers, Weight-0 parent poses and
PublishedId. Usage: python make_install.py <clip> ... (or --all = every JSON listed in art/anim/body/clips.txt)."""
import json, os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
J = os.path.join(ROOT, "out/anim_body/json")
names = sys.argv[1:]
if names == ["--all"]:
    names = [l.strip() for l in open(os.path.join(ROOT, "art/anim/body/clips.txt")) if l.strip() and not l.startswith("#")]
pub = {}
pp = os.path.join(ROOT, "art/anim/body/published.json")
if os.path.exists(pp):
    pub = json.load(open(pp))
hp = os.path.join(ROOT, "art/anim/body/published_hash.json")
hashes = json.load(open(hp)) if os.path.exists(hp) else {}
clips = []
for n in names:
    d = json.load(open(os.path.join(J, n + ".json")))
    d.pop("quality", None)
    if n in pub and hashes.get(n) and hashes[n] != d["attrs"]["SourceHash"]:
        print("STALE id dropped (clip changed after upload):", n)
        pub.pop(n)
    clips.append(d)
build = open(os.path.join(ROOT, "art/anim/body/studio/build_clips.lua"), encoding="utf-8").read()
out = ["-- install_sources.lua (generated by art/anim/body/tools/make_install.py; do not edit by hand)",
       "-- Final Tacticals body / movement clips (anim-body). Creates/replaces ReplicatedStorage.Repository.AnimationSources.<Clip>",
       "-- and sets PublishedId (group gunsy funsy) where published. Edit mode, command bar or MCP execute_luau.",
       "local CLIPS_JSON = [==[" + json.dumps(clips, separators=(",", ":")) + "]==]",
       "local PUBLISHED = game:GetService(\"HttpService\"):JSONDecode([==[" + json.dumps(pub) + "]==])"]
body = build.replace("\treturn ks\nend", "\tif PUBLISHED[clip.name] then ks:SetAttribute(\"PublishedId\", PUBLISHED[clip.name]) end\n\treturn ks\nend", 1)
out.append(body)
dst = os.path.join(ROOT, "art/anim/body/install_sources.lua")
open(dst, "w", encoding="utf-8").write("\n".join(out))
print(dst, len(clips), "clips", len(pub), "published", os.path.getsize(dst) // 1024, "KB")
