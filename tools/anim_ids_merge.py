"""Make fix/anim_ids_merge.lua [ANIMIDS]: run the animators' install_sources.lua files without ever losing a live animation.
Usage: python -I tools/anim_ids_merge.py      (reads art/anim/weapons/published.json and art/anim/body/published.json if present)
Then in Studio (Edit):  run_luau_at <id> fix/anim_ids_merge.lua PRE   ->  the animators' install_sources.lua  ->  ... POST
  PRE  : copies every AnimationSources clip that has a PublishedId into ServerStorage._AnimSourcesPre1030 (once; kept for UNDO)
  POST : sets PublishedId from the published lists on the clips of the same name (the animators' uploads, group gunsy funsy);
         then any clip that still has no PublishedId but had one before PRE is put back to its old published version (a new
         clip not uploaded yet would play nothing live). Reports: ids applied, old clips kept, new clips still unpublished.
  UNDO : puts every backed-up clip back and removes the backup (the animators' new clips without an old version stay)."""
import json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ids = {}
for f in ("art/anim/weapons/published.json", "art/anim/body/published.json"):
    p = os.path.join(ROOT, f)
    if os.path.exists(p):
        d = json.load(open(p, encoding="utf-8"))
        if isinstance(d, dict):
            for k, v in d.items():
                if isinstance(v, str) and v.startswith("rbxassetid://"): ids[k] = v
                elif isinstance(v, dict) and str(v.get("id", "")).startswith("rbxassetid://"): ids[k] = v["id"]
lua_ids = ",\n".join(f'\t[{json.dumps(k)}] = {json.dumps(v)}' for k, v in sorted(ids.items()))
LUA = '''-- fix/anim_ids_merge.lua [ANIMIDS] (GENERATED by tools/anim_ids_merge.py; %d published ids)
local MODE = "POST" --@MODE (PRE / POST / UNDO)
local IDS = {
%s
}
local SRC = game.ReplicatedStorage.Repository.AnimationSources
local SS = game:GetService("ServerStorage")
local bak = SS:FindFirstChild("_AnimSourcesPre1030")
if MODE == "PRE" then
	if bak then return "PRE: backup already there (" .. #bak:GetChildren() .. " clips)" end
	bak = Instance.new("Folder")
	bak.Name = "_AnimSourcesPre1030"
	bak:SetAttribute("Readme", "[ANIMIDS] the published clips before the final animation install (fix/anim_ids_merge.lua UNDO)")
	for _, c in SRC:GetChildren() do
		if c:GetAttribute("PublishedId") then c:Clone().Parent = bak end
	end
	bak.Parent = SS
	return "PRE: backed up " .. #bak:GetChildren() .. " published clips"
elseif MODE == "POST" then
	local applied, kept, unpub = 0, {}, {}
	for _, c in SRC:GetChildren() do
		local id = IDS[c.Name]
		if id and c:GetAttribute("PublishedId") ~= id then c:SetAttribute("PublishedId", id) applied += 1 end
	end
	for _, c in SRC:GetChildren() do
		if not c:GetAttribute("PublishedId") then
			local old = bak and bak:FindFirstChild(c.Name)
			if old then
				c:Destroy()
				old:Clone().Parent = SRC
				table.insert(kept, old.Name)
			elseif c:GetAttribute("SourceHash") then
				table.insert(unpub, c.Name)
			end
		end
	end
	return ("POST: %%d ids applied | %%d old published clips kept (new one not uploaded): %%s | %%d new clips not uploaded (play in Studio only): %%s"):format(
		applied, #kept, table.concat(kept, ","), #unpub, table.concat(unpub, ","))
elseif MODE == "UNDO" then
	if not bak then return "UNDO: no backup" end
	local n = 0
	for _, old in bak:GetChildren() do
		local cur = SRC:FindFirstChild(old.Name)
		if cur then cur:Destroy() end
		old:Clone().Parent = SRC
		n += 1
	end
	bak:Destroy()
	return "UNDO: " .. n .. " clips put back"
end
''' % (len(ids), lua_ids)
open(os.path.join(ROOT, "fix/anim_ids_merge.lua"), "w", encoding="utf-8", newline="\n").write(LUA)
print(f"wrote fix/anim_ids_merge.lua ({len(ids)} ids)")
