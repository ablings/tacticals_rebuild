"""Build fix/ui_survey_r2.lua [UISURVEY2]: the UI survey round 2 source changes as anchor edits on the LIVE scripts.

Why anchors and not ui/deploy_ui.py: several ui/ files are behind the places (CoverController lacks the [GLASS] edit, the
MOVE1029 installer edits scripts in place), so a whole-file deploy would roll other sessions' work back. Here every change
is (old -> new) text with enough context to be unique; the installer refuses a script whose anchor is missing or doubled
and changes nothing in that script (it prints which). Idempotent: an edit whose new text is already there is skipped.

Usage: python tools/ui_survey_r2_build.py [base_commit]   (default base: f714708e~1, the commit before the survey work)
Writes fix/ui_survey_r2.lua (run it in Studio Edit through execute_luau; then the place patches below run too).
"""
