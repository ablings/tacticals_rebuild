"""Run the RankedCore unit tests (scripts/ranked/tests/unit_tests.lua + fixture_v2.lua) in Edit through the stdio MCP bridge.
Usage (from tacticals_rebuild): python tools/ranked_test.py [lobby|match]   (default lobby)
The fixture is generated from tools/ranked_table.py (the reference): python tools/ranked_test.py --fixture rewrites it first
(the 21 x 21 gain / loss table + Edward's 2v2 team check, 2026-10-17)."""
import json, os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
SIDS = {"lobby": "5e5685e4-6afe-4dde-b307-dd6c67c0a85d", "match": "7a8bab8a-3a9c-479b-b323-38d82789723b"}
CLI = r"C:\Users\aroki\Documents\rivals_practice\mcpcli.py"
T = os.path.join(ROOT, "scripts", "ranked", "tests")

if "--fixture" in sys.argv:
    sys.path.insert(0, HERE)
    import ranked_table as rt
    g = ",".join(str(rt.gain(m, o)) for m in range(21) for o in range(21))
    l = ",".join(str(rt.loss(m, o)) for m in range(21) for o in range(21))
    # Edward's 2v2 check: Commander 1 + Bronze 1 vs Platinum 1 x2 -> Commander win / loss, Bronze win / loss
    c, b = rt.team(18, [18, 0], [9, 9]), rt.team(0, [18, 0], [9, 9])
    team = ",".join(str(v) for v in (c[0], c[1], b[0], b[1]))
    open(os.path.join(T, "fixture_v2.lua"), "w", newline="\n").write(
        "-- generated by python from tools/ranked_table.py (v2, commit b7ddd07; team() 2026-10-17): gain / loss for every tier (0..20)\n"
        "-- vs every tier, row-major; team = Edward's 2v2 check (Commander win, loss, Bronze win, loss)\n"
        f"return {{ gain = {{ {g} }}, loss = {{ {l} }}, team = {{ {team} }} }}\n")
place = next((a for a in sys.argv[1:] if a in SIDS), "lobby")
fixture = open(os.path.join(T, "fixture_v2.lua"), encoding="utf-8").read().replace("return {", "local FIXTURE = {", 1)
code = fixture + "\n" + open(os.path.join(T, "unit_tests.lua"), encoding="utf-8").read()
fd, path = tempfile.mkstemp(suffix=".json"); os.close(fd)
json.dump({"studio_id": SIDS[place], "datamodel_type": "Edit", "code": code}, open(path, "w", encoding="utf-8"))
r = subprocess.run([sys.executable, CLI, "call", "execute_luau", path], capture_output=True, text=True, encoding="utf-8",
                   env=dict(os.environ, PYTHONIOENCODING="utf-8", MCP_TIMEOUT="120"))
print(r.stdout); print(r.stderr[-2000:], file=sys.stderr); os.remove(path)
sys.exit(r.returncode or (0 if ", 0 failed" in r.stdout else 1))
