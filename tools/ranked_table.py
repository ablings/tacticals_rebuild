"""Generates notes/ranked_elo_table.md from Edward's ranked rules (v2, 2026-10-16; team() = Edward's answers 2026-10-17).
Gap is measured in tiers (3 per rank)."""
R = ["Bronze", "Silver", "Gold", "Platinum", "Diamond", "Elite", "Commander"]
WIN = [30, 28, 25, 21, 17, 13, 10]   # beat someone your own rank
LOSS = [10, 12, 15, 18, 21, 23, 25]  # lose to someone your own rank

def base(table, tier):  # in-between ranks: interpolate by tier (tier 0 = Bronze 1 ... 20 = Commander 3)
    r = tier / 3
    i = min(int(r), 5)
    return table[i] + (table[i + 1] - table[i]) * (r - i) if r < 6 else table[6]

def gain(me, opp):  # me / opp = tier index
    d = (opp - me) / 3
    w = base(WIN, me)
    v = w * (2 ** 0.5) ** d if d >= 0 else w * (0.4 ** 0.5) ** -d
    return max(1, min(100, round(v)))

def loss(me, opp):
    d = (opp - me) / 3
    l = base(LOSS, me)
    if d >= 0:  # lost to someone stronger: smaller loss
        v = l * (0.5 ** 0.5) ** d
    else:       # lost to someone weaker: straight line to 60 at 2 ranks below, then to 100 at 6 ranks below
        g = -d
        v = l + (60 - l) * g / 2 if g <= 2 else 60 + 40 * (g - 2) / 4
    return max(1, min(100, round(v)))

def team(me, own, opp):  # Edward 2026-10-17: effective tier = (own tier + own team's average tier) / 2 vs the other team's average
    eff = (me + sum(own) / len(own)) / 2
    o = sum(opp) / len(opp)
    return gain(eff, o), loss(eff, o)

if __name__ == "__main__":
    T = lambda r: r * 3  # tier 1 of each rank
    checks = [("Bronze 1 beats Bronze 1", gain(0, 0), 30), ("Bronze 1 beats Gold 1", gain(0, T(2)), 60),
              ("Bronze 1 loses to Bronze 1", loss(0, 0), 10), ("Bronze 1 loses to Gold 1", loss(0, T(2)), 5),
              ("Gold 1 beats Gold 1", gain(T(2), T(2)), 25), ("Gold 1 beats Bronze 1", gain(T(2), 0), 10),
              ("Gold 1 loses to Gold 1", loss(T(2), T(2)), 15), ("Gold 1 loses to Bronze 1", loss(T(2), 0), 60),
              ("Commander beats Commander", gain(T(6), T(6)), 10), ("Commander loses to Commander", loss(T(6), T(6)), 25),
              ("Commander loses to Diamond (max 60)", loss(T(6), T(4)), 60)]
    checks += [("2v2 Commander (+Bronze) vs Plat+Plat win", team(T(6), [T(6), 0], [T(3), T(3)])[0], 8),
               ("2v2 Commander (+Bronze) vs Plat+Plat loss", team(T(6), [T(6), 0], [T(3), T(3)])[1], 50),
               ("2v2 Bronze (+Commander) vs Plat+Plat win", team(0, [T(6), 0], [T(3), T(3)])[0], 45),
               ("2v2 Bronze (+Commander) vs Plat+Plat loss", team(0, [T(6), 0], [T(3), T(3)])[1], 8)]
    for n, g, w in checks:
        print(f"{n:38s} {g:4d}  (Edward: {w})  {'OK' if g == w else 'DIFF'}")
    hdr = r"| You \ vs | " +" | ".join(r[:4] for r in R) + " |"
    sep = "|---|" + "---|" * len(R)
    out = ["## Win: ELO you GAIN for beating each rank (tier 1 vs tier 1)", hdr, sep]
    out += [f"| **{R[m]}** | " + " | ".join(f"+{gain(T(m), T(o))}" for o in range(7)) + " |" for m in range(7)]
    out += ["", "## Loss: ELO you LOSE for losing to each rank (tier 1 vs tier 1)", hdr, sep]
    out += [f"| **{R[m]}** | " + " | ".join(f"-{loss(T(m), T(o))}" for o in range(7)) + " |" for m in range(7)]
    names = [f"{r[:4]}{t+1}" for r in R for t in range(3)]
    out += ["", "## Every tier (rows = you, columns = opponent): win / loss", "| | " + " | ".join(names) + " |", "|---|" + "---|" * 21]
    out += [f"| **{names[m]}** | " + " | ".join(f"+{gain(m, o)}/-{loss(m, o)}" for o in range(21)) + " |" for m in range(21)]
    open("notes/ranked_elo_table.md", "w", encoding="utf-8").write(
        "# Ranked ELO table v2 (generated by tools/ranked_table.py from Edward's rules, 2026-10-16)\n\n" + "\n".join(out) + "\n")
    print("\n".join(out[:20]))
