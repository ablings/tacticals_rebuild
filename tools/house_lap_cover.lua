-- client step 3: cover on furniture (low + tall), vault the kitchen pass-through and the island, Space at a window sill and at
-- the gallery railing must not climb
char = lp.Character; hum = char:FindFirstChildOfClass("Humanoid"); root = char:FindFirstChild("HumanoidRootPart")
local function cov(name, x0, y0, h, x1, y1)
	place(x0, y0, h, x1 - x0, y1 - y0)
	local r = act("Cover", x1, y1, h + 2)
	task.wait(0.8)
	log(string.format("cover %-26s %s", name, fmt(act("none"))))
	return r
end
local function space(name, x1, y1, h)
	local r = act("Jump", x1, y1, h + 2)
	waitIdle(2.5)
	log(string.format("   Space %-20s -> %s", name, where()))
	act("Cover"); waitIdle(1.5)
end
