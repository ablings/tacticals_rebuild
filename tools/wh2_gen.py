"""Warehouse 2 generator: writes the LAYOUT block of fix/map_warehouse2.lua from the old Warehouse's measured gameplay layer.

    python tools/wh2_gen.py            (rewrites the block between "-- @LAYOUT BEGIN" and "-- @LAYOUT END")

Source: notes/warehouse_study/warehouse_dump.json (the Warehouse's CollisionProxies, spawns and shootables, dumped read-only from
the Tutorial place on 2026-10-26; geom.py's plan coords: e east = -(x - CX), n north = z - CZ, h above the floor top 0.4).
Every cover piece and both spawns keep their plan position, size and cover role (work order 2026-10-27); only the surface
(material -> impact sound) follows the new look. Never hand-edit the generated block: change this file and re-run it.
"""
import json, math, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "notes", "warehouse_study"))
import geom  # noqa: E402

LUA = os.path.join(ROOT, "fix", "map_warehouse2.lua")
DOOR_HALF = 10  # the roll-up openings are 20 wide (map_warehouse2.lua DOOR_HALF)

# the new look of each cover kind (Warehouse 2 brief): proxy material decides the bullet sound (ImpactSounds.Classify)
KINDS = {
    "pillar": dict(look="PalletStack", mat="Cardboard"),   # two shrink-wrapped pallet loads, 5x10x5
    "block": dict(look="TallCrate", mat="WoodPlanks"),     # plywood shipping crate, 5x7x4
    "wall": dict(look="BlockWall", mat="Concrete"),        # interlocking precast concrete blocks, 10x7x3
    "low": dict(look="Jersey", mat="Concrete"),            # jersey barrier, 6x3.4x2
}


def r3(v):
    v = round(v, 3)
    return 0.0 if v == 0 else v


def main():
    D = geom.D
    rows = []
    for q in sorted(geom.pieces, key=lambda q: q["id"]):
        k = KINDS[q["kind"]]
        rows.append('\t\t{ id = "%s", kind = "%s", look = "%s", mat = "%s", e = %s, n = %s, w = %s, d = %s, h = %s },' % (
            q["id"], q["kind"], k["look"], k["mat"], r3(q["e"]), r3(q["n"]), r3(q["w"]), r3(q["d"]), r3(q["h"])))
    sp = []
    for p in D["spawns"]:
        e = -(p["pos"][0] - geom.CX); n = p["pos"][2] - geom.CZ
        yaw = math.radians(p["rot"][1])
        # the marker's LookVector in world (rot y = yaw about +Y): (-sin yaw, 0, -cos yaw)
        lx, lz = -math.sin(yaw), -math.cos(yaw)
        # full precision: the old markers sit 0.00007 off the half-stud grid; rounding them moved the study's spawn cell by one
        # row (spawn floor view -8 % / +11 %, metrics run 2026-10-27)
        sp.append('\t\t%s = { e = %r, n = %r, h = %r, lookX = %r, lookZ = %r, size = { %s, %s, %s } },' % (
            p["name"][-1], e, n, p["pos"][1] - geom.FY, lx, lz, *[r3(s) for s in p["size"]]))
    sh = {}
    for p in D["shootables"]:
        sh.setdefault(p["parent"], p)
    shr = []
    for name in sorted(sh):
        # model position = its Body (barrels) / ValveBody (valves) part
        body = next((p for p in D["shootables"] if p["parent"] == name and p["name"] in ("Body", "ValveBody")), sh[name])
        shr.append('\t\t{ id = "%s", e = %s, n = %s },' % (name, r3(-(body["pos"][0] - geom.CX)), r3(body["pos"][2] - geom.CZ)))
    # the old camera skin (wall bumps): same names and plan rectangles, minus the ones inside the new 20-wide doors. The
    # Warehouse 2 walls are built on it (piers / cabinets), so the free floor near the walls is the old one (metrics run 2026-10-27)
    sk = []
    for c in sorted(geom.camskin, key=lambda c: c["name"]):
        nm = c["name"]
        e0, e1, n0, n1 = c["e"] - c["w"] / 2, c["e"] + c["w"] / 2, c["n"] - c["d"] / 2, c["n"] + c["d"] / 2
        wall = nm.split("Wall_")[1].split("_")[0]
        if wall in ("N", "S") and e0 < DOOR_HALF + 0.6 and e1 > -DOOR_HALF - 0.6:
            continue
        proud = {"E": geom.HALF_W - e0, "W": geom.HALF_W + e1, "N": geom.HALF_L - n0, "S": geom.HALF_L + n1}[wall]
        sk.append('\t\t{ name = "%s", wall = "%s", e0 = %s, e1 = %s, n0 = %s, n1 = %s, proud = %s },' % (
            nm, wall, r3(e0), r3(e1), r3(n0), r3(n1), r3(proud)))
    block = "\n".join([
        "-- @LAYOUT BEGIN",
        "local LAYOUT = { -- generated by tools/wh2_gen.py from notes/warehouse_study/warehouse_dump.json (never hand-edit)",
        "\tsource = { CX = %s, CZ = %s, FY = %s }, -- the old Warehouse's plan origin (world x, z of the hall centre; floor top y)" % (geom.CX, geom.CZ, geom.FY),
        "\thall = { halfE = %s, halfN = %s }, -- inside faces: 81 x 114" % (geom.HALF_W, geom.HALF_L),
        "\tpieces = {",
        *rows,
        "\t},",
        "\tspawns = {",
        *sp,
        "\t},",
        "\tskin = { -- the old CamSkin, kept: same names and footprint (the walls' piers are built on it)",
        *sk,
        "\t},",
        "\tshootables = { -- read-back only: the installer clones Workspace.Warehouse.Shootables and moves it",
        *shr,
        "\t},",
        "}",
        "-- @LAYOUT END",
    ])
    src = open(LUA, encoding="utf-8").read()
    new = re.sub(r"-- @LAYOUT BEGIN.*?-- @LAYOUT END", lambda m: block, src, flags=re.S)
    if new == src and "-- @LAYOUT BEGIN" not in src:
        sys.exit("no @LAYOUT markers in " + LUA)
    open(LUA, "w", encoding="utf-8", newline="\n").write(new)
    print("LAYOUT: %d pieces, %d spawns, %d skin rects, %d shootables -> %s" % (len(rows), len(sp), len(sk), len(shr), LUA))


if __name__ == "__main__":
    main()
