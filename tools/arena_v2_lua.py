"""Write the Arena v2 layout (notes/maps/arena_v2_layout.json) into fix/map_arena.lua as a Luau data block.

    python -I tools/arena_v2_lua.py          (re-run after tools/arena_v2_layout.py changes the JSON)

The block sits between the lines '-- @LAYOUT BEGIN' and '-- @LAYOUT END' in fix/map_arena.lua; everything else in the
builder is hand-written. Plan axes: x east, y north, z up from the floor top; the builder maps them to the world as
ORIGIN + (x, FLOOR_TOP + z, -y). Every number is checked to sit on the 0.5 grid (exit 1 otherwise).
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
D = json.load(open(os.path.join(ROOT, "notes", "maps", "arena_v2_layout.json"), encoding="utf-8"))
LUA = os.path.join(ROOT, "fix", "map_arena.lua")


def num(v):
    if abs(v * 2 - round(v * 2)) > 1e-6 and abs(v * 10 - round(v * 10)) > 1e-6:
        sys.exit(f"off-grid value {v}")
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


off_grid = []
lines = ["local LAYOUT = { -- generated by tools/arena_v2_lua.py from notes/maps/arena_v2_layout.json (version %d)" % D["version"]]
b = D["box"]
lines.append("\tbox = { x0 = %s, x1 = %s, y0 = %s, y1 = %s, h = %s, t = %s }," % tuple(num(b[k]) for k in ("x0", "x1", "y0", "y1", "wall_h", "wall_t")))
lines.append("\tpieces = {")
for p in D["pieces"]:
    parts = []
    for q in p["parts"]:
        for k in ("x0", "x1", "y0", "y1"):
            if abs(q[k] * 2 - round(q[k] * 2)) > 1e-6:
                off_grid.append((p["id"], k, q[k]))
        parts.append("{ %q, %s, %s, %s, %s, %s, %s }".replace("%q", '"%s"') % (q["role"], *(num(q[k]) for k in ("x0", "x1", "y0", "y1", "z0", "z1"))))
    ramp = ""
    if p.get("ramp"):
        r = p["ramp"]
        ramp = ", ramp = { foot = { %s, %s }, top = { %s, %s }, width = %s, rise = %s }" % (
            num(r["foot"][0]), num(r["foot"][1]), num(r["top"][0]), num(r["top"][1]), num(r["width"]), num(r["rise"]))
    lines.append('\t\t{ id = "%s", kind = "%s", side = "%s", parts = { %s }%s },' % (p["id"], p["kind"], p["side"], ", ".join(parts), ramp))
lines.append("\t},")
lines.append("\tspawns = {")
for team in ("A", "B"):
    s = D["spawns"][team]
    lines.append("\t\t%s = { pocket = { %s }, spot = { %s, %s }, face = { %s, %s } }," % (
        team, ", ".join(num(v) for v in s["pocket"]), num(s["spots"][0][0]), num(s["spots"][0][1]), num(s["face"][0]), num(s["face"][1])))
lines.append("\t},")
lines.append("}")
if off_grid:
    sys.exit("off the 0.5 grid: %s" % off_grid)

src = open(LUA, encoding="utf-8").read()
new = re.sub(r"-- @LAYOUT BEGIN\n.*?-- @LAYOUT END\n", lambda m: "-- @LAYOUT BEGIN\n" + "\n".join(lines) + "\n-- @LAYOUT END\n", src, flags=re.S)
if new == src and "-- @LAYOUT BEGIN" not in src:
    sys.exit("markers not found in fix/map_arena.lua")
open(LUA, "w", encoding="utf-8", newline="\n").write(new)
n_parts = sum(len(p["parts"]) for p in D["pieces"])
n_ramps = sum(1 for p in D["pieces"] if p.get("ramp"))
print(f"layout block written: {len(D['pieces'])} pieces, {n_parts} parts + {n_ramps} ramps")
