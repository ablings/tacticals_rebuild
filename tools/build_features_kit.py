"""Builds fix/place_features_kit.lua (feature props kit placement) from kit/features_manifest.json + scripts/features_kit/place_body.lua.
Run: python tools/build_features_kit.py, then python tools/run_luau.py fix/place_features_kit.lua [UNDO]   (Tacticals_rebuild.rbxl only).
Report: notes/features_kit_place.md"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
man = json.load(open(os.path.join(ROOT, "kit", "features_manifest.json"), encoding="utf-8"))

def b(v): return "true" if v else "false"
lines = ["local MESH = {  -- generated from kit/features_manifest.json: {r,g,b, material, variant, collide, query, notCover, fidelity, transparency, castShadow, overlay, role}"]
for m in man["meshes"]:
    if m["piece"] not in man["pieces"]:
        continue
    r, g, bl = m["rgb"]
    lines.append('\t["%s"] = {%d, %d, %d, "%s", "%s", %s, %s, %s, "%s", %s, %s, "%s", "%s"},' % (
        m["name"], r, g, bl, m["material_studio"], m["variant"] or "", b(m["can_collide"]), b(m["can_query"]), b(m["not_cover"]),
        m["collision_fidelity"], m["transparency"], b(m["cast_shadow"]), m["texture_overlay"], m["role"]))
lines.append("}")
lines.append("local PIECE = {  -- pivot_studio (template row position) and bounds relative to the pivot")
for k, p in man["pieces"].items():
    mn, mx = p["bounds_rel_pivot"]["min"], p["bounds_rel_pivot"]["max"]
    lines.append('\t%s = {pivot = Vector3.new(%s, %s, %s), min = Vector3.new(%s, %s, %s), max = Vector3.new(%s, %s, %s)},' % (
        k, *p["pivot_studio"], *mn, *mx))
lines.append("}")

body = open(os.path.join(ROOT, "scripts", "features_kit", "place_body.lua"), encoding="utf-8").read()
head = '''--[[ fix/place_features_kit.lua : place the feature props kit (kit/features.fbx, imported to ServerStorage.features) in
Tacticals_rebuild.rbxl (LOCAL copy only; never the live place). GENERATED by tools/build_features_kit.py from
kit/features_manifest.json + scripts/features_kit/place_body.lua: edit those, then rebuild.
Idempotent (every run first undoes the previous one). UNDO = true puts everything back. Runs AFTER fix/install_features.lua
(a re-install rebuilds LobbyMap.Features, so re-run this afterwards) and fix/place_training.lua (same for the Training bins/crates).
Runner: python tools/run_luau.py fix/place_features_kit.lua [UNDO]      Report: notes/features_kit_place.md ]]
local UNDO = false --@UNDO
'''
open(os.path.join(ROOT, "fix", "place_features_kit.lua"), "w", encoding="utf-8", newline="\n").write(head + "\n".join(lines) + "\n" + body)
print("written fix/place_features_kit.lua")
