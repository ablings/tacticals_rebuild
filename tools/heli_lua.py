"""Fill the generated tables of fix/place_heli.lua (--@MESH) and fix/check_heli.lua (--@PROXY) from kit/heli_manifest.json.
Usage (from tacticals_rebuild): python tools/heli_lua.py   (run after tools/heli_kit.py)"""
import json, os, re
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
man = json.load(open(os.path.join(R, "kit", "heli_manifest.json")))
b = lambda v: "true" if v else "false"
rows = []
for m in man["meshes"]:
    if m["piece"].startswith(("K_", "REF_")):
        continue
    c, s = m["center_studio"], m["size_studio"]
    rows.append('\t["%s"] = {%d, %d, %d, "%s", %s, %s, "%s", %s, %g, %g, "%s", %g, %g, %g, %g, %g, %g},' % (
        m["name"], *m["rgb"], m["studio_material"], b(m["collide"]), b(m["query"]), m["fidelity"], b(m["cast_shadow"]),
        m["transparency"], m["reflectance"], m["rotor"], *c, *s))
mesh_lua = "local MESH = { -- generated by tools/heli_lua.py --@MESH\n" + "\n".join(rows) + "\n}"
prox_lua = "local PROXIES = { -- generated by tools/heli_lua.py --@PROXY\n" + "\n".join(
    '\t{%g, %g, %g, %g, %g, %g, "%s"},' % tuple(p) for p in man["proxies"]) + "\n}"
def fill(path, tag, text):
    p = os.path.join(R, path); s = open(p, encoding="utf-8").read()
    pat1 = re.compile(r"^local (MESH|PROXIES) = \{\} --@" + tag + r"[ \t]*$", re.M)
    pat2 = re.compile(r"^local (MESH|PROXIES) = \{ -- generated[^\n]*--@" + tag + r"\n.*?\n\}[ \t]*$", re.M | re.S)
    s2, n = pat1.subn(lambda _: text, s, count=1)
    if n == 0:
        s2, n = pat2.subn(lambda _: text, s, count=1)
    assert n == 1, (path, tag)
    open(p, "w", encoding="utf-8").write(s2)
fill("fix/place_heli.lua", "MESH", mesh_lua)
fill("fix/check_heli.lua", "PROXY", prox_lua)
print("MESH rows", len(rows), "proxies", len(man["proxies"]))
