"""Builds fix/install_features.lua (lobby feature pass: Edward's picks 3, 4, 18-21, 23, 29-32) from scripts/features/*.lua.
Run: python tools/build_features.py, then python tools/run_luau.py fix/install_features.lua [UNDO]   (Tacticals_rebuild.rbxl only).
The installer is idempotent: it removes what an earlier run made (modules with attribute LF_New, LobbyMap.Features,
Signs.Screen_Leaderboard with LF_New) and builds it again. No existing script is edited (EDITS is empty; the [FEAT] edit
machinery is kept so a later minimal edit can be added the same way as the Training extras). UNDO removes everything and gives
the two Duels floor meshes their collision back. Report: notes/features_done.md"""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "scripts", "features")

MGR = 'game.ServerScriptService.ServerScripts["[Server] Init"].GameManager.Managers'
CTL = 'game.StarterPlayer.StarterPlayerScripts.Client.Controllers'
NEW = [  # (parent expr, name, file)
    ('game.ReplicatedStorage.Modules.Shared.Config', "LobbyFeaturesConfig", "LobbyFeaturesConfig.lua"),
    (MGR, "LobbyFeaturesManager", "LobbyFeaturesManager.lua"),
    (CTL, "LobbyScreensController", "LobbyScreensController.lua"),
    (CTL, "LobbyFeaturesFXController", "LobbyFeaturesFXController.lua"),
]
EDITS = []  # (script expr, key, [(old, new)]) -- every new line would carry a [FEAT] marker; none needed in this pass


def lstr(s):
    n = 0
    while ("]" + "=" * n + "]") in s:
        n += 1
    return "[" + "=" * n + "[\n" + s + "]" + "=" * n + "]"


out = ['''--[[ fix/install_features.lua : lobby feature pass in Tacticals_rebuild.rbxl (LOCAL copy only). GENERATED by
tools/build_features.py from scripts/features/*.lua: edit those, then rebuild. Idempotent; UNDO removes it all.
Report: notes/features_done.md ]]
local UNDO = false --@UNDO
local SS = game:GetService("ServerStorage")
local log = {}
local function say(...) local t = {} for i = 1, select("#", ...) do t[i] = tostring((select(i, ...))) end table.insert(log, table.concat(t, " ")) end
local ORIG = SS:FindFirstChild("_FEAT_Originals")
''']
out.append(open(os.path.join(SRC, "_geometry.lua"), encoding="utf-8").read())
out.append("local NEW = {")
for parent, name, f in NEW:
    src = open(os.path.join(SRC, f), encoding="utf-8").read()
    out.append("\t{function() return " + parent + ' end, "' + name + '", ' + lstr(src) + "},")
out.append("}")
out.append("local EDITS = {")
for expr, key, pairs in EDITS:
    ps = ", ".join("{" + lstr(o) + ", " + lstr(n) + "}" for o, n in pairs)
    out.append(f"\t{{function() return {expr} end, \"{key}\", {{{ps}}}}},")
out.append("}")
out.append('''
-- remove an earlier install (geometry) and give the Duels floor its collision back
local function removeGeometry()
	local F = LM:FindFirstChild("Features"); if F and F:GetAttribute("LF_New") then F:Destroy(); say("removed LobbyMap.Features") end
	local lb = LM.Signs:FindFirstChild("Screen_Leaderboard"); if lb and lb:GetAttribute("LF_New") then lb:Destroy(); say("removed Signs.Screen_Leaderboard") end
	for _, d in LM:GetDescendants() do
		if d:IsA("BasePart") and d:GetAttribute("LF_OrigCollide") ~= nil then
			d.CanCollide = d:GetAttribute("LF_OrigCollide"); d:SetAttribute("LF_OrigCollide", nil); say("collision restored", d.Name)
		end
	end
	local off = SS:FindFirstChild("_LobbyFeaturesOff"); if off then off:Destroy() end
end

if UNDO then
	for _, e in EDITS do
		local scr = e[1](); local v = ORIG and ORIG:FindFirstChild(e[2])
		if v then scr.Source = v.Value; say("restored", e[2]) end
	end
	for _, n in NEW do
		local par = n[1](); local m = par:FindFirstChild(n[2])
		if m and m:GetAttribute("LF_New") then m:Destroy(); say("removed", n[2]) end
	end
	removeGeometry()
	if ORIG then ORIG:Destroy() end
	say("UNDO done")
	return table.concat(log, "\\n")
end
local existing = LM.Signs:FindFirstChild("Screen_Leaderboard")
if existing and not existing:GetAttribute("LF_New") then error("Signs.Screen_Leaderboard exists and is not ours: not touching it") end
for _, n in NEW do
	local par = n[1]()
	local m = par:FindFirstChild(n[2])
	if m and not m:GetAttribute("LF_New") then error("a module named " .. n[2] .. " already exists at " .. m:GetFullName() .. " (not ours)") end
	if not m then m = Instance.new("ModuleScript"); m.Name = n[2]; m:SetAttribute("LF_New", true); m.Parent = par end
	m.Source = n[3]
	say("module", m:GetFullName(), #n[3])
end
for _, e in EDITS do
	local scr = e[1]()
	if not ORIG then ORIG = Instance.new("Folder"); ORIG.Name = "_FEAT_Originals"; ORIG.Parent = SS end
	local v = ORIG:FindFirstChild(e[2])
	if not v then v = Instance.new("StringValue"); v.Name = e[2]; v.Value = scr.Source; v.Parent = ORIG end
	local src = v.Value
	for i, pair in e[3] do
		local a, b = string.find(src, pair[1], 1, true)
		if not a then error("edit " .. e[2] .. " #" .. i .. ": original text not found") end
		src = string.sub(src, 1, a - 1) .. pair[2] .. string.sub(src, b + 1)
	end
	scr.Source = src
end
removeGeometry()
buildGeometry(say)
return table.concat(log, "\\n")
''')
open(os.path.join(ROOT, "fix", "install_features.lua"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("written fix/install_features.lua")
